export function categoriesFor(pack: PackId, custom: string[] = []) {
  const categories =
    pack === "kids"
      ? kidsCategories
      : pack === "adults"
        ? adultCategories
        : pack === "mixed"
          ? [...kidsCategories, ...familyExtras, ...adultCategories]
          : [...kidsCategories, ...familyExtras];
  return [...new Set([...categories, ...custom])];
}
